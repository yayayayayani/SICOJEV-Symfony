<?php

namespace App\Repository;

use App\Entity\Usuario;
use Doctrine\Bundle\DoctrineBundle\Repository\ServiceEntityRepository;
use Doctrine\Persistence\ManagerRegistry;
use Symfony\Bridge\Doctrine\Security\User\UserLoaderInterface;
use Symfony\Component\Security\Core\Exception\UnsupportedUserException;
use Symfony\Component\Security\Core\User\PasswordAuthenticatedUserInterface;
use Symfony\Component\Security\Core\User\PasswordUpgraderInterface;

/**
 * @extends ServiceEntityRepository<Usuario>
 */
class UsuarioRepository extends ServiceEntityRepository implements PasswordUpgraderInterface, UserLoaderInterface
{
    public function __construct(ManagerRegistry $registry)
    {
        parent::__construct($registry, Usuario::class);
    }

    public function loadUserByIdentifier(string $identifier): ?Usuario
    {
        $identifier = trim($identifier);
        if ($identifier === '') {
            return null;
        }

        $usuarios = $this->createQueryBuilder('u')
            ->where('u.username = :identifier OR LOWER(TRIM(u.correo)) = :correo')
            ->setParameter('identifier', $identifier)
            ->setParameter('correo', mb_strtolower($identifier))
            ->setMaxResults(2)
            ->getQuery()
            ->getResult();

        // Un correo duplicado o un identificador ambiguo no debe elegir otra cuenta.
        return count($usuarios) === 1 ? $usuarios[0] : null;
    }

    /**
     * Used to upgrade (rehash) the user's password automatically over time.
     */
    public function upgradePassword(PasswordAuthenticatedUserInterface $user, string $newHashedPassword): void
    {
        if (!$user instanceof Usuario) {
            throw new UnsupportedUserException(sprintf('Instances of "%s" are not supported.', $user::class));
        }

        $user->setPassword($newHashedPassword);
        $this->getEntityManager()->persist($user);
        $this->getEntityManager()->flush();
    }

